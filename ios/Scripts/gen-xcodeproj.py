def configs(name, extra):
    d = add('cfg-' + name + '-Debug', 'XCBuildConfiguration', {'buildSettings': dict(extra), 'name': 'Debug'}, 'Debug')
    r = add('cfg-' + name + '-Release', 'XCBuildConfiguration', {'buildSettings': dict(extra), 'name': 'Release'}, 'Release')
    return add('cl-' + name, 'XCConfigurationList', {'buildConfigurations': [d, r], 'defaultConfigurationIsVisible': '0',
                                                      'defaultConfigurationName': 'Release'}, 'Build configuration list for ' + name)

def target(name, ptype, product_ref, phases, groups, deps, pkgs, settings):
    return add('target-' + name, 'PBXNativeTarget', {
        'buildConfigurationList': configs(name, settings), 'buildPhases': phases, 'buildRules': [],
        'dependencies': deps, 'fileSystemSynchronizedGroups': groups, 'name': name,
        'packageProductDependencies': pkgs, 'productName': name, 'productReference': product_ref,
        'productType': ptype}, name)

