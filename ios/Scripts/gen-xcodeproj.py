def oid(name):
    return hashlib.md5(name.encode()).hexdigest()[:24].upper()

objs = {}   # id -> (isa-section, text)
def add(name, isa, body, comment=None):
    i = oid(name)
    objs[i] = (isa, body, comment or name)
    return i

def q(s):
    if s == '' or any(c in s for c in ' -+=$()[]{}<>,;"*@/\\:.\'') and not s.replace('_','').isalnum():
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return s

def fmt(v, ind):
    t = '\t' * ind
    if isinstance(v, dict):
        out = '{\n'
        for k, x in v.items():
            out += t + '\t' + q(k) + ' = ' + fmt(x, ind + 1) + ';\n'
        return out + t + '}'
    if isinstance(v, list):
        out = '(\n'
        for x in v:
            out += t + '\t' + fmt(x, ind + 1) + ',\n'
        return out + t + ')'
    return q(str(v))

